// Внешнему AI передаётся только один из заранее заданных общих вопросов.
// Исходный текст пользователя остаётся на сервере приложения.
const TOPICS = [
  [/предпринимател|бизнес|сво[её] дел|самозанят|соцконтракт/, 'Какие общие меры помогают участнику СВО открыть своё дело?'],
  [/стро.*дом|постро.*дом|земельн|участок/, 'Какие общие меры помогают участнику СВО построить жилой дом?'],
  [/работ|ваканс|трудоустр|резюме/, 'Как участнику СВО найти работу и получить помощь службы занятости?'],
  [/обуч|переобуч|професси|курс/, 'Какие общие возможности обучения доступны участнику СВО?'],
  [/психолог|психическ|тревог|стресс/, 'Где участнику СВО получить психологическую помощь?'],
  [/реабилитац|лечени|здоров|медицин|инвалидност/, 'Какие общие меры медицинской помощи и реабилитации доступны участнику СВО?'],
  [/удостоверен|статус|ветеран/, 'Как участнику СВО оформить статус ветерана боевых действий?'],
  [/юрист|жалоб|суд|правов/, 'Где участнику СВО получить юридическую помощь?'],
  [/жиль|квартир|ипотек|переезд/, 'Какие общие жилищные меры доступны участнику СВО?'],
  [/пенси|выплат|пособ|льгот|субсиди|компенсац/, 'Какие общие выплаты и льготы доступны участнику СВО?'],
  [/семь|ребен|ребён|погиб|вдов/, 'Какие общие меры поддержки доступны семьям участников СВО?'],
];

export function buildSafeAiQuestion(query) {
  const text = typeof query === 'string' ? query.toLocaleLowerCase('ru') : '';
  return TOPICS.find(([pattern]) => pattern.test(text))?.[1]
    || 'Где участнику СВО и его семье узнать о доступных мерах поддержки?';
}
